def clause_of(text: str) -> str:
    """从使用说明里切出基本物耗条款原文（含「不另行收费」结论）。"""
    if not text:
        return ""
    keys = ["物耗成本计入项目价格", "物质资源消耗成本计入项目价格", "相关成本计入项目价格"]
    pos = -1
    for k in keys:
        pos = text.find(k)
        if pos >= 0:
            break
    if pos < 0:
        return ""
    # 条目清单在结论句之前：从「…所称的」后面那个定义词起切，别被清单末尾的「等。」截断，
    # 也别把上一句「扩展项」带进来（病理、检验这类条款结尾没句号，按句号回退会多切一句）
    d = text.rfind("所称", 0, pos)
    d = 0 if d < 0 else d
    cand = [(text.find(k, d), k) for k in ("基本物耗", "基本物质资源消耗", "基本物质资源物耗")]
    cand = [(i, k) for i, k in cand if 0 <= i < pos]
    if not cand:
        return ""
